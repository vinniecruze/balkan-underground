-- Starter schema only. Review before production.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  character_name text,
  gender text,
  skin_id integer not null default 0 check (skin_id between 0 and 311),
  avatar_url text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  created_at timestamptz not null default now(),
  author_id uuid references auth.users(id)
);
alter table public.profiles enable row level security;
alter table public.news enable row level security;
create policy "profiles read authenticated" on public.profiles for select to authenticated using (true);
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid()=id) with check (auth.uid()=id);
create policy "users insert own profile" on public.profiles for insert to authenticated with check (auth.uid()=id);
create policy "news readable by everyone" on public.news for select using (true);
-- IMPORTANT: Do not enable public news insert/update/delete until admin authorization
-- is implemented with a trusted role assignment (never let users self-set role='admin').
