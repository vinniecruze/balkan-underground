-- Pokreni u Supabase Dashboard > SQL Editor.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 username text unique,
 gender text check (gender in ('male','female')),
 avatar_url text,
 character_name text,
 skin_id integer check (skin_id between 0 and 311),
 role text not null default 'user' check (role in ('user','admin')),
 created_at timestamptz not null default now()
);
create table if not exists public.news (
 id bigint generated by default as identity primary key,
 title text not null,
 body text not null,
 author_id uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.news enable row level security;
create or replace function public.is_bu_admin() returns boolean language sql stable security definer set search_path=public as $$ select exists(select 1 from public.profiles where id=auth.uid() and role='admin'); $$;
drop policy if exists "profiles readable by signed-in users" on public.profiles;
create policy "profiles readable by signed-in users" on public.profiles for select to authenticated using (true);
drop policy if exists "users insert own profile" on public.profiles;
create policy "users insert own profile" on public.profiles for insert to authenticated with check (id=auth.uid() and role='user');
drop policy if exists "users update own profile or admin" on public.profiles;
create policy "users update own profile or admin" on public.profiles for update to authenticated using (id=auth.uid() or public.is_bu_admin()) with check (id=auth.uid() or public.is_bu_admin());
drop policy if exists "news readable by everyone" on public.news;
create policy "news readable by everyone" on public.news for select to anon, authenticated using (true);
drop policy if exists "admins insert news" on public.news;
create policy "admins insert news" on public.news for insert to authenticated with check (public.is_bu_admin());
drop policy if exists "admins update news" on public.news;
create policy "admins update news" on public.news for update to authenticated using (public.is_bu_admin()) with check (public.is_bu_admin());
drop policy if exists "admins delete news" on public.news;
create policy "admins delete news" on public.news for delete to authenticated using (public.is_bu_admin());
