-- Automatsko kreiranje profila posle registracije.
create or replace function public.bu_handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id, username, gender, role)
 values(new.id, coalesce(new.raw_user_meta_data->>'username', split_part(new.email,'@',1)), new.raw_user_meta_data->>'gender', 'user')
 on conflict (id) do nothing;
 return new;
end; $$;
drop trigger if exists bu_on_auth_user_created on auth.users;
create trigger bu_on_auth_user_created after insert on auth.users for each row execute procedure public.bu_handle_new_user();
-- Spreči korisnika da sam sebi dodeli admin ulogu.
create or replace function public.bu_protect_role() returns trigger language plpgsql security definer set search_path=public as $$
begin
 if new.role is distinct from old.role and not public.is_bu_admin() then raise exception 'Only an admin can change roles'; end if;
 return new;
end; $$;
drop trigger if exists bu_role_guard on public.profiles;
create trigger bu_role_guard before update on public.profiles for each row execute procedure public.bu_protect_role();
